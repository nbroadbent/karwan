#!/bin/bash
# Regenerates playlist.js from the audio files in this folder.
# Usage: ./music/make-playlist.sh     (then reload the game)
cd "$(dirname "$0")"
{
  echo "// Generated by make-playlist.sh — audio files in this folder."
  echo "window.USER_PLAYLIST = ["
  for f in *.mp3 *.m4a *.aac *.ogg *.oga *.wav *.flac *.opus; do
    [ -e "$f" ] || continue
    title="${f%.*}"; artist=""
    if [[ "$title" == *" - "* ]]; then artist="${title%% - *}"; title="${title#* - }"; fi
    esc() { printf '%s' "$1" | sed "s/\\\\/\\\\\\\\/g; s/'/\\\\'/g"; }
    echo "  { file: '$(esc "$f")', title: '$(esc "$title")', artist: '$(esc "$artist")' },"
  done
  echo "];"
} > playlist.js
echo "Wrote $(grep -c "file:" playlist.js) song(s) to music/playlist.js"
